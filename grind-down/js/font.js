// 3x5 pixel font. Each glyph: 15 bits, row-major.
const G = {
  A: '010101111101101', B: '110101110101110', C: '011100100100011', D: '110101101101110',
  E: '111100110100111', F: '111100110100100', G: '011100101101011', H: '101101111101101',
  I: '111010010010111', J: '001001001101010', K: '101101110101101', L: '100100100100111',
  M: '101111111101101', N: '110101101101101', O: '010101101101010', P: '110101110100100',
  Q: '010101101110011', R: '110101110101101', S: '011100010001110', T: '111010010010010',
  U: '101101101101011', V: '101101101010010', W: '101101111111101', X: '101101010101101',
  Y: '101101010010010', Z: '111001010100111',
  0: '111101101101111', 1: '010110010010111', 2: '110001010100111', 3: '110001010001110',
  4: '101101111001001', 5: '111100110001110', 6: '011100111101111', 7: '111001010010010',
  8: '111101111101111', 9: '111101111001110',
  ':': '000010000010000', '.': '000000000000010', '!': '010010010000010', '-': '000000111000000',
  '/': '001001010100100', "'": '010010000000000', '?': '110001010000010', '>': '100010001010100',
  '<': '001010100010001', '+': '000010111010000', ',': '000000000010100', ' ': '000000000000000',
};

export const textWidth = (s, scale = 1) => (String(s).length * 4 - 1) * scale;

function raw(ctx, s, x, y, col, scale) {
  ctx.fillStyle = col;
  for (let i = 0; i < s.length; i++) {
    const g = G[s[i]];
    if (!g) continue;
    for (let p = 0; p < 15; p++) {
      if (g[p] === '1') ctx.fillRect(x + (i * 4 + (p % 3)) * scale, y + Math.floor(p / 3) * scale, scale, scale);
    }
  }
}

export function drawText(ctx, str, x, y, col, { scale = 1, align = 'left', shadow = null } = {}) {
  const s = String(str).toUpperCase();
  const w = textWidth(s, scale);
  if (align === 'center') x -= Math.floor(w / 2);
  else if (align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  if (shadow) raw(ctx, s, x + scale, y + scale, shadow, scale);
  raw(ctx, s, x, y, col, scale);
}
